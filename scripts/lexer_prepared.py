"""Source/config-bound compiled lexer maps; no runtime decoder or public API."""
import hashlib
import json
from pathlib import Path

BUNDLE = 'benchmarks/lexerpreparedinput'
HEADER = 'mysys/mariamem_lexer_prepared.h'
INPUT_SHA256 = 'ee25a76714132ace3a28a10bc2a1083dc1f839c87a6966da56f7585a14757078'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def validate(root, source=None):
    root = Path(root)
    bundle = root / BUNDLE
    raw = (bundle / 'input.json').read_bytes()
    if digest(raw) != INPUT_SHA256:
        raise ValueError('lexer input identity changed')
    value = json.loads(raw)
    guest = json.loads((root / 'guest/input.json').read_text())
    if value['schema'] != 1 or value['mariadb_source_commit'] != guest['source_commit']:
        raise ValueError('lexer MariaDB source mismatch')
    if source is not None:
        for name, expected in value['pristine_sha256'].items():
            if not (Path(source) / name).is_file() or digest((Path(source) / name).read_bytes()) != expected:
                raise ValueError('lexer pristine source changed: ' + name)
    data = bytes.fromhex(value['data_hex'])
    bindings = value['bindings']
    if len(data) != 28 * 512 or digest(data) != value['data_sha256'] or len(bindings) != 638:
        raise ValueError('lexer payload/census mismatch')
    if any(str(int(n)) != n or type(p) is not int or not 0 <= p < 28 for n, p in bindings.items()):
        raise ValueError('invalid lexer descriptor/pair')
    wrapper = (bundle / 'wrapper.c.inc').read_bytes()
    if digest(wrapper) != value['wrapper_sha256']:
        raise ValueError('lexer wrapper changed')
    parts = ['/* Compiled boot descriptors only. Generated by scripts/lexer_prepared.py. */\n',
             'static const uchar mariamem_lexer_pairs[28][512] = {\n']
    for i in range(28):
        pair = data[i * 512:(i + 1) * 512]
        parts.append('{\n' + ',\n'.join(','.join(map(str, pair[j:j + 32])) for j in range(0, 512, 32)) + '\n},\n')
    parts.append('};\nstatic const uchar *mariamem_lexer_lookup(uint number)\n{\n  switch (number) {\n')
    for number, pair in sorted(bindings.items(), key=lambda item: int(item[0])):
        parts.append(f'    case {number}: return mariamem_lexer_pairs[{pair}];\n')
    parts.append('    default: return NULL;\n  }\n}\n\n')
    parts.append(wrapper.decode())
    header = ''.join(parts).encode()
    record = {'contract': 'prepared-lexer-v1', 'input_sha256': INPUT_SHA256,
              'generator_sha256': digest((root / 'scripts/lexer_prepared.py').read_bytes()),
              'wrapper_sha256': value['wrapper_sha256'], 'header': HEADER,
              'header_sha256': digest(header), 'descriptors': 638, 'numeric_bytes': len(data)}
    return header, record


def prepare(root, source):
    header, record = validate(root, source)
    with (Path(source) / HEADER).open('xb') as output:
        output.write(header)
    return record


def verify_record(root, record):
    if record != validate(root)[1]:
        raise ValueError('prepared lexer source-input provenance differs')
