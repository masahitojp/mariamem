"""Refresh derived license bindings while preserving audit and policy pins."""
import argparse
from contextlib import contextmanager
import fcntl
import hashlib
import json
import os
from pathlib import Path
import tempfile
from distribution_licenses import inventory, verify_generated_attribution

ROOT = Path(__file__).resolve().parents[1]
LEDGERS = ('release/generated-license-evidence.json',
           'release/distribution-licenses.json', 'python/license-inventory.json')
JOURNAL = 'build/evidence-records-update.json'


def encoded(value):
    return (json.dumps(value, indent=2)+'\n').encode()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def planned_updates(root):
    root = Path(root)
    if (root/JOURNAL).exists():
        raise ValueError('unfinished ledger update; run --update to recover and retry')
    value = inventory(root)  # Reject changed notices and an unbound evidence record.
    evidence = json.loads((root/LEDGERS[0]).read_text())
    pins = json.loads((root/'release/generated-go-inputs.json').read_text())
    build = json.loads((root/'release/generated-go-build.json').read_text())
    if not (evidence['guest_sha256'] == pins['guest_sha256'] == build['guest_sha256'] and
            evidence['linked_sha256'] == build['linked_guest_sha256']):
        raise ValueError('guest/link identity changed; a new audit is required')
    kind = verify_generated_attribution(root, evidence)
    provenance = root/'internal/generatedgo/provenance.json'
    record = json.loads(provenance.read_text())
    for name, expected in record['files_sha256'].items():
        if (not name or Path(name).is_absolute() or '\\' in name or
                any(part in ('', '.', '..') for part in name.split('/'))):
            raise ValueError('invalid generated path')
        if sha((provenance.parent/name).read_bytes()) != expected:
            raise ValueError('generated bytes differ: '+name)
    # Never replace the original audit pin or its historical host/symbol facts.
    evidence.pop('metadata_only_provenance_sha256', None)
    if kind == 'exact':
        evidence.pop('attribution_continuity', None)
    else:
        evidence['attribution_continuity'] = {
            'kind': kind,
            'audited_provenance_sha256': evidence['generated_provenance_sha256'],
            'current_provenance_sha256': sha(provenance.read_bytes()),
            'policy_sha256': sha((root/'release/attribution-tolerance.json').read_bytes()),
        }
    raw = encoded(evidence)
    value['evidence_sha256'] = sha(raw)
    proposed = {LEDGERS[0]: raw, LEDGERS[1]: encoded(value), LEDGERS[2]: encoded(value)}
    return {name: data for name, data in proposed.items() if (root/name).read_bytes() != data}


def atomic_write(path, data):
    """Replace one complete file; the journal handles the multi-file boundary."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix='.'+path.name+'.', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temp, path.stat().st_mode & 0o777 if path.exists() else 0o644)
        os.replace(temp, path)
        sync_directory(path.parent)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def sync_directory(path):
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


@contextmanager
def ledger_lock(root):
    path = Path(root)/'build/evidence-records-update.lock'
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        yield


def recover_update(root):
    """Roll back a recorded partial update, refusing intervening user edits."""
    root = Path(root)
    path = root/JOURNAL
    if not path.exists():
        return False
    journal = json.loads(path.read_text())
    if (set(journal) != {'version', 'files'} or journal['version'] != 1 or
            not isinstance(journal['files'], dict) or not journal['files'] or
            set(journal['files']) - set(LEDGERS)):
        raise ValueError('invalid ledger recovery journal')
    # Validate every target before writing any rollback bytes.
    for name, row in journal['files'].items():
        if (set(row) != {'before', 'after'} or
                any(not isinstance(row[k], str) for k in ('before', 'after'))):
            raise ValueError('invalid ledger recovery entry')
        if (root/name).read_bytes() not in (row['before'].encode(), row['after'].encode()):
            raise ValueError('ledger changed since interrupted update: '+name)
    for name, row in journal['files'].items():
        atomic_write(root/name, row['before'].encode())
    path.unlink()
    sync_directory(path.parent)
    return True


def apply_updates(root, updates):
    """Caller holds ledger_lock; journal persists across abrupt termination."""
    root = Path(root)
    if not updates:
        return
    if set(updates) - set(LEDGERS) or (root/JOURNAL).exists():
        raise ValueError('invalid or unfinished ledger update')
    rows = {name: {'before': (root/name).read_bytes().decode(), 'after': data.decode()}
            for name, data in updates.items()}
    atomic_write(root/JOURNAL, encoded({'version': 1, 'files': rows}))
    try:
        for name, data in updates.items():
            atomic_write(root/name, data)
    except OSError:
        recover_update(root)
        raise
    (root/JOURNAL).unlink()
    sync_directory((root/JOURNAL).parent)


def main(argv=None, *, root=ROOT):
    root = Path(root)
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--update', action='store_true')
    args = parser.parse_args(argv)
    try:
        with ledger_lock(root):
            if args.update and recover_update(root):
                print('Recovered interrupted ledger update; validating current inputs.')
            updates = planned_updates(root)
            for name, data in updates.items():
                print(f'{name}: {sha((root/name).read_bytes())} -> {sha(data)}')
            if args.update:
                apply_updates(root, updates)
            elif updates:
                parser.exit(1, 'Derived ledger differs: run scripts/update_evidence_records.py --update and review the diff.\n')
    except (ValueError, KeyError, OSError) as exc:
        parser.exit(1, f'{exc}\n')


if __name__ == '__main__':
    main()
