"""Single-guest CRC32C binding, applied by the canonical runtime installer.

This is not a general WASM optimizer. The whole original validator and its
constant table must match before replacing its CRC calculation. All callers,
stored-checksum comparisons, LSN checks and other validation branches survive.
"""
import hashlib
import re

GUEST_SHA256 = '5f8b711f8efe31529c12847a093e92b8f962598e035cb1d5e253e41093feee20'
PATH = 'code/p4/p4_pure.go'
FUNCTION = 'Fn18145'
BODY_SHA256 = '2569b9f4e7022921787050ec11e7fae5b14382416adc732fae562c8f6aca236e'
TABLE_SHA256 = 'aa14839f04e2220eb7b6543158c9e0bee0f787fdd2ee2f2ee83125aa5a373dad'
TABLE_OFFSET = 7930560
TABLE_SIZE = 4096
CRC_BLOCKS = {'L23', *(f'L{i}' for i in range(37, 80))}


def validate_inputs(guest_sha256, data):
    table = data[TABLE_OFFSET:TABLE_OFFSET + TABLE_SIZE]
    if guest_sha256 != GUEST_SHA256 or hashlib.sha256(table).hexdigest() != TABLE_SHA256:
        raise ValueError('unreviewed CRC32C guest/table binding')


def function(text):
    starts = list(re.finditer(r'(?m)^func ' + FUNCTION + r'\(', text))
    if len(starts) != 1:
        raise ValueError('CRC32C validator missing/duplicate')
    tail = text[starts[0].start():]
    following = re.search(r'\nfunc ', tail)
    body = tail[:following.start()] if following else tail
    if hashlib.sha256(body.encode()).hexdigest() != BODY_SHA256:
        raise ValueError('CRC32C original validator changed; re-review binding')
    return body


def apply(name, text):
    if name != PATH:
        return text
    original = function(text)
    parts = re.split(r'\n(L\d+):\n', original)
    blocks = {parts[i]: parts[i + 1] for i in range(1, len(parts), 2)}
    # These are the reviewed computation-only blocks. Nothing may enter their
    # interior or leave them except through the original checksum comparison.
    for label, body in blocks.items():
        edges = set(re.findall(r'goto (L\d+)', body))
        if label in CRC_BLOCKS:
            if not edges or edges - CRC_BLOCKS - {'L36'} or 'return ' in body or re.search(r'Fn\d+\(', body):
                raise ValueError('CRC32C computation boundary changed')
        elif edges & (CRC_BLOCKS - {'L23'}):
            raise ValueError('CRC32C interior has an external entry')
    updated = parts[0]
    for i in range(1, len(parts), 2):
        label, body = parts[i:i + 2]
        if label == 'L23':
            updated += '\nL23:\n\tv495 = int64(^base.CRC32C(m, l1, v40))\n\tgoto L36\n'
        elif label not in CRC_BLOCKS:
            updated += '\n' + label + ':\n' + body
    return text.replace(original, updated, 1)


def reference_source(text):
    """Keep the exact original validator in test-only Go for differential tests."""
    body = function(text)
    body = body.replace('func ' + FUNCTION + '(', 'func originalCRCValidator(', 1)
    body = re.sub(r'\b(Fn\d+)\(', r'p4.\1(', body)
    return ('// Code generated by scripts/runtime_crc32c.py; DO NOT EDIT.\n'
            '// Exact original validator; compiled only by tests.\npackage p4_test\n'
            'import (\n\t"github.com/masahitojp/mariamem/internal/generatedgo/code/base"\n'
            '\t"github.com/masahitojp/mariamem/internal/generatedgo/code/p4"\n'
            '\t"sync/atomic"\n\t"unsafe"\n)\n' + body + '\n')
